"""
Daily Market Analytics Report Generator.
Produces human-readable Markdown reports and stable machine-readable JSON outputs.
"""

from typing import Dict, List, Any
import json


class DailyReportGenerator:
    """Generates structured daily Markdown report and JSON analysis export."""

    def generate_markdown_report(self, analysis_data: Dict[str, Any]) -> str:
        date_str = analysis_data.get("date", "N/A")
        market = analysis_data.get("market", {})
        sectors = analysis_data.get("sectors", [])
        stocks = analysis_data.get("stocks", [])
        quality = analysis_data.get("data_quality", {})

        # Top / Bottom scoring stocks
        sorted_stocks = sorted(stocks, key=lambda x: x.get("technical_score", 0), reverse=True)
        top_stocks = sorted_stocks[:5]
        bottom_stocks = sorted_stocks[-5:] if len(sorted_stocks) >= 5 else []

        # Technical events
        breakouts = [s["symbol"] for s in stocks if s.get("signals", {}).get("breakout_20d", False)]
        unusual_vol = [s["symbol"] for s in stocks if s.get("signals", {}).get("unusual_volume", False)]

        md = f"""# Daily Indian Stock Market Analysis - {date_str}

## Executive Market Summary
* **Benchmark Market Regime:** {market.get('regime', 'N/A')} (Score: {market.get('regime_score', 0)}/100)
* **Market Breadth (% Stocks > 20 DMA):** {market.get('pct_above_20dma', 0)}%
* **Advance / Decline Ratio:** {market.get('advance_decline_ratio', 1.0)} ({market.get('advances', 0)} Advances / {market.get('declines', 0)} Declines)
* **20-Day New Highs / Lows:** {market.get('new_highs_20d', 0)} Highs / {market.get('new_lows_20d', 0)} Lows

---

## Sector Performance & Rankings
| Rank | Sector | Daily Return (%) | Weekly Return (%) | Relative Strength vs Benchmark (%) | Momentum Score |
| :--- | :--- | :--- | :--- | :--- | :--- |
"""
        for sec in sectors:
            md += f"| {sec.get('rank', '-')} | {sec.get('sector', '')} | {sec.get('daily_return', 0)}% | {sec.get('weekly_return', 0)}% | {sec.get('relative_strength_1d', 0)}% | {sec.get('momentum_score', 0)} |\n"

        md += """
---

## Stock Composite Rankings

### Top Performing / Strongest Stocks
| Ticker | Sector | Score | Label | RSI (14) | Volatility Regime | 5D Forward Bias | Confidence |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |
"""
        for s in top_stocks:
            fwd = s.get("forward_probabilities", {}).get("5d", {})
            md += f"| {s.get('symbol')} | {s.get('sector')} | {s.get('technical_score')} | {s.get('score_label')} | {s.get('rsi_14')} | {s.get('volatility_regime')} | {fwd.get('directional_bias', 'Neutral')} | {fwd.get('confidence', 50)}% |\n"

        if bottom_stocks:
            md += """
### Lowest Scoring / Weakest Stocks
| Ticker | Sector | Score | Label | RSI (14) | Volatility Regime | 5D Forward Bias | Confidence |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |
"""
            for s in bottom_stocks:
                fwd = s.get("forward_probabilities", {}).get("5d", {})
                md += f"| {s.get('symbol')} | {s.get('sector')} | {s.get('technical_score')} | {s.get('score_label')} | {s.get('rsi_14')} | {s.get('volatility_regime')} | {fwd.get('directional_bias', 'Neutral')} | {fwd.get('confidence', 50)}% |\n"

        md += f"""
---

## Technical Events & Screening
* **20-Day Breakouts:** {', '.join(breakouts) if breakouts else 'None detected'}
* **Unusual Volume Spikes (>2x 20MA):** {', '.join(unusual_vol) if unusual_vol else 'None detected'}

---

## Historical Pattern Analogues & Probabilistic Futures
*Note: Forward probabilities represent historical empirical conditional statistics from matching technical setups and do NOT constitute guaranteed forecasts.*

"""
        for s in top_stocks[:3]:
            fwd_dict = s.get("forward_probabilities", {})
            f_5d = fwd_dict.get("5d", {})
            md += f"### {s.get('symbol')} (Historical Analogues Found: {s.get('historical_analogue_matches', 0)})\n"
            md += f"- **1-Day Expected Return (Avg / Win Rate):** {fwd_dict.get('1d', {}).get('avg_forward_return', 0)}% ({fwd_dict.get('1d', {}).get('positive_probability', 0)}% positive)\n"
            md += f"- **5-Day Expected Return (Avg / Win Rate):** {f_5d.get('avg_forward_return', 0)}% ({f_5d.get('positive_probability', 0)}% positive)\n"
            md += f"- **20-Day Expected Return (Avg / Win Rate):** {fwd_dict.get('20d', {}).get('avg_forward_return', 0)}% ({fwd_dict.get('20d', {}).get('positive_probability', 0)}% positive)\n\n"

        md += f"""---

## Data Quality Summary
* **Records Processed:** {quality.get('records_processed', 0)}
* **Records Valid:** {quality.get('records_valid', 0)}
* **Warnings Logged:** {len(quality.get('warnings', []))}
* **Errors Logged:** {len(quality.get('errors', []))}

---

*Report automatically generated by Indian Stock Market Data & Analytics Pipeline on {date_str}.*
"""
        return md
