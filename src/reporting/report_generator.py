import json
import logging
from typing import Dict, Any, List

logger = logging.getLogger(__name__)


class ReportGenerator:
    """Generates daily Markdown summary reports and validates machine-readable JSON output."""

    @staticmethod
    def generate_markdown_report(
        date_str: str,
        market_data: Dict[str, Any],
        sector_data: Dict[str, Any],
        stock_scores: List[Dict[str, Any]],
        quality_data: Dict[str, Any]
    ) -> str:
        """Generates a structured daily Markdown research report."""

        # Sort stocks by score
        sorted_stocks = sorted(stock_scores, key=lambda x: x.get("technical_score", 0), reverse=True)
        top_stocks = sorted_stocks[:5]
        bottom_stocks = sorted_stocks[-5:] if len(sorted_stocks) >= 5 else []

        # Find technical events across universe
        breakouts = []
        breakdowns = []
        unusual_vol = []
        for s in stock_scores:
            sym = s.get("symbol")
            signals = s.get("signals", {})
            events = signals.get("events", [])
            for ev in events:
                if "Breakout" in ev:
                    breakouts.append(sym)
                elif "Breakdown" in ev:
                    breakdowns.append(sym)
                elif "Unusual Volume" in ev:
                    unusual_vol.append(sym)

        breadth = market_data.get("breadth", {})

        report = f"""# Daily Indian Stock Market Research & Deep Analysis Report
**Date:** {date_str}
**Generated By:** Automated Indian Stock Market Analysis Pipeline

---

## 1. Market Summary & Regime
- **Market Regime:** {market_data.get("regime", "Neutral")} (Confidence: {market_data.get("confidence_score", 50)}%)
- **NIFTY 50 Close:** {market_data.get("nifty_close", 0):,.2f} ({market_data.get("nifty_return_1d", 0)*100:+.2f}%)
- **NIFTY Trend:** {market_data.get("nifty_trend", "Neutral")}
- **BANK NIFTY Trend:** {market_data.get("banknifty_trend", "Neutral")}
- **Market Volatility (NIFTY 20D):** {market_data.get("nifty_volatility", 0)*100:.2f}%
- **Market Breadth:**
  - Advance / Decline Ratio: {breadth.get("advance_decline_ratio", 1.0)} ({breadth.get("advances", 0)} Advances / {breadth.get("declines", 0)} Declines)
  - % Stocks Above 20 DMA: {breadth.get("pct_above_20dma", 50)}%
  - % Stocks Above 50 DMA: {breadth.get("pct_above_50dma", 50)}%
  - % Stocks Above 200 DMA: {breadth.get("pct_above_200dma", 50)}%
  - New 52-Week Highs / Lows: {breadth.get("new_52w_highs", 0)} Highs / {breadth.get("new_52w_lows", 0)} Lows

> *Classification Rule Note:* Market regime is classified using rule-based technical and breadth thresholds. See architecture documentation for exact formulas.

---

## 2. Sector Performance
### Sector Leaders
"""
        for sec in sector_data.get("sectors", [])[:3]:
            report += f"- **{sec['sector']}**: {sec['return_1d']:+.2f}% 1D | Momentum Score: {sec['momentum_score']} | Leaders: {', '.join(sec['leaders'])}\n"

        report += "\n### Sector Laggards\n"
        for sec in sector_data.get("sectors", [])[-3:]:
            report += f"- **{sec['sector']}**: {sec['return_1d']:+.2f}% 1D | Momentum Score: {sec['momentum_score']} | Laggards: {', '.join(sec['laggards'])}\n"

        report += f"""
---

## 3. Stock Highlights

### Highest Scoring Stocks (Strong / Very Strong)
"""
        for s in top_stocks:
            report += f"- **{s['symbol']}**: Score = {s['technical_score']} ({s['composite_label']}) | 1D Return = {s.get('signals', {}).get('return_1d', 0)*100:+.2f}% | RSI = {s.get('signals', {}).get('rsi_14', 50):.1f}\n"

        report += "\n### Lowest Scoring Stocks (Weak / Very Weak)\n"
        for s in bottom_stocks:
            report += f"- **{s['symbol']}**: Score = {s['technical_score']} ({s['composite_label']}) | 1D Return = {s.get('signals', {}).get('return_1d', 0)*100:+.2f}% | RSI = {s.get('signals', {}).get('rsi_14', 50):.1f}\n"

        report += f"""
---

## 4. Technical Events & Price Action
- **20-Day High Breakouts:** {', '.join(breakouts) if breakouts else 'None detected'}
- **20-Day Low Breakdowns:** {', '.join(breakdowns) if breakdowns else 'None detected'}
- **Unusual Volume Surge:** {', '.join(unusual_vol) if unusual_vol else 'None detected'}

---

## 5. Forward Probabilities & Historical Analogues
"""
        for s in top_stocks[:2]:
            analogues = s.get("historical_analogues", {})
            fwd = s.get("forward_probabilities", {})
            report += f"### {s['symbol']}\n"
            report += f"- Historical Matches Found: {analogues.get('matches_count', 0)}\n"
            if "forward_statistics" in analogues and "5d" in analogues["forward_statistics"]:
                f5 = analogues["forward_statistics"]["5d"]
                report += f"- 5-Day Historical Win Rate: {f5.get('positive_probability')}% | Avg Forward Return: {f5.get('average_return_pct')}%\n"
            report += f"- Directional Research Bias (5D): {fwd.get('directional_bias', 'Neutral')} (Confidence: {fwd.get('confidence', 50)}%)\n\n"

        report += f"""---

## 6. Data Quality & Pipeline Status
- **Records Processed:** {quality_data.get("records_processed", 0)}
- **Records Valid:** {quality_data.get("records_valid", 0)}
- **Warnings Recorded:** {len(quality_data.get("warnings", []))}
- **Errors Recorded:** {len(quality_data.get("errors", []))}

---

## 7. Financial Safeguards & Research Notes
*This report is generated automatically for statistical research and quantitative analysis purposes only. Forward directional biases and historical analogue probabilities represent empirical historical observations and statistical inference, NOT guaranteed future price movements. Never treat pipeline outputs as investment advice.*
"""
        return report

    @staticmethod
    def build_daily_json_schema(
        date_str: str,
        market_data: Dict[str, Any],
        sector_data: Dict[str, Any],
        stock_scores: List[Dict[str, Any]]
    ) -> Dict[str, Any]:
        """Constructs stable machine-readable JSON analysis output."""
        return {
            "date": date_str,
            "market": market_data,
            "sectors": sector_data.get("sectors", []),
            "stocks": stock_scores
        }
