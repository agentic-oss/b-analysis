import pandas as pd
import numpy as np
from typing import Dict, Any, List, Optional

class FeatureEngineer:
    """Generates feature datasets specifically designed for machine learning models, strictly avoiding lookahead bias."""

    @staticmethod
    def create_feature_dataset(
        df_stock: pd.DataFrame,
        market_df: Optional[pd.DataFrame] = None,
        sector_df: Optional[pd.DataFrame] = None,
        horizons: List[int] = [1, 3, 5, 10, 20]
    ) -> pd.DataFrame:
        """
        Builds a feature matrix for a stock.
        Features for date T use strictly information available up to date T.
        Forward target columns (e.g. future_return_1d) are generated by shifting close prices backward (t + horizon).
        """
        if df_stock.empty or len(df_stock) < 10:
            return pd.DataFrame()

        df = df_stock.sort_values('date').copy().reset_index(drop=True)

        features = pd.DataFrame()
        features['date'] = df['date']
        features['symbol'] = df['symbol']

        # Price & Volume Features
        features['price_open'] = df['open']
        features['price_high'] = df['high']
        features['price_low'] = df['low']
        features['price_close'] = df['close']
        features['volume'] = df['volume']

        # Returns
        features['return_1d'] = df['close'].pct_change(1)
        features['return_5d'] = df['close'].pct_change(5)
        features['return_20d'] = df['close'].pct_change(20)

        # Technical Indicators (reuse calculated if present, or compute)
        features['rsi_14'] = df.get('rsi_14', 50.0)
        features['stoch_rsi'] = df.get('stoch_rsi', 0.5)
        features['macd'] = df.get('macd', 0.0)
        features['macd_signal'] = df.get('macd_signal', 0.0)
        features['atr_14'] = df.get('atr_14', 0.0)
        features['volatility_20d'] = df.get('volatility_20d', 0.15)

        features['sma_20'] = df.get('sma_20', df['close'])
        features['sma_50'] = df.get('sma_50', df['close'])
        features['sma_200'] = df.get('sma_200', df['close'])
        features['ema_20'] = df.get('ema_20', df['close'])

        features['relative_volume'] = df.get('relative_volume', 1.0)
        features['distance_from_52w_high'] = df.get('dist_52w_high', 0.0)
        features['distance_from_52w_low'] = df.get('dist_52w_low', 0.0)

        # Market & Sector features if available
        if market_df is not None and not market_df.empty and 'return_1d' in market_df.columns:
            mkt_cols = ['date', 'return_1d']
            if 'volatility_20d' in market_df.columns:
                mkt_cols.append('volatility_20d')
            mkt = market_df[mkt_cols].copy()
            col_map = {'return_1d': 'market_return_1d', 'volatility_20d': 'market_volatility'}
            mkt = mkt.rename(columns=col_map)
            features = pd.merge(features, mkt, on='date', how='left')
            if 'market_volatility' not in features.columns:
                features['market_volatility'] = 0.15
        else:
            features['market_return_1d'] = 0.0
            features['market_volatility'] = 0.15

        if sector_df is not None and not sector_df.empty and 'return_1d' in sector_df.columns:
            sec = sector_df[['date', 'return_1d']].copy().rename(columns={'return_1d': 'sector_return_1d'})
            features = pd.merge(features, sec, on='date', how='left')
            features['sector_return_1d'] = features['sector_return_1d'].fillna(0.0)
        else:
            features['sector_return_1d'] = 0.0

        # --- PREVENT LOOKAHEAD BIAS FOR TARGET GENERATION ---
        # Future Target Columns for training (shifted by horizon)
        for h in horizons:
            # Shift (-h) brings future close price to current date row T
            future_close = df['close'].shift(-h)
            features[f'target_future_return_{h}d'] = (future_close - df['close']) / df['close']
            features[f'target_direction_{h}d'] = (features[f'target_future_return_{h}d'] > 0).astype(int)

        return features
